a = 10
b = 5

print(f"{a} + {b} = {a + b}")
print(f"{a} - {b} = {a - b}")
print(f"{a} × {b} = {a * b}")
print(f"{a} ÷ {b} = {a / b}")
print(f"{a} ÷ {b} (ปัดลง) = {a // b}")
print(f"{a} หาร {b} เหลือเศษ = {a % b}")
print(f"{a} ยกกำลัง {b} = {a ** b}")

